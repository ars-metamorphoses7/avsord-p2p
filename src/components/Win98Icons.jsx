// Precompute horizontal RLE rects per sprite for fast, crisp SVG rendering.
const RECT_CACHE = new Map();

function rectsFor(name) {
  let cached = RECT_CACHE.get(name);
  if (cached) return cached;
  const rows = SPRITES[name] || SPRITES.computer;
  const rects = [];
  for (let y = 0; y < rows.length; y += 1) {
    const row = rows[y];
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      if (ch === '.' || !PALETTE[ch]) {
        x += 1;
        continue;
      }
      let end = x + 1;
      while (end < row.length && row[end] === ch) end += 1;
      rects.push({ x, y, w: end - x, fill: PALETTE[ch] });
      x = end;
    }
  }
  RECT_CACHE.set(name, rects);
  return rects;
}

export const PixelIcon = memo(function PixelIcon({ name, size = 16, className = '', title }) {
  const rects = rectsFor(name);
  return (
    <svg
      className={`win-icon win-pixel-icon ${className}`.trim()}
      width={size}
      height={size}
      viewBox="0 0 16 16"
      shapeRendering="crispEdges"
      aria-hidden="true"
      focusable="false"
    >
      {title && <title>{title}</title>}
      {rects.map((rect, index) => (
        <rect key={index} x={rect.x} y={rect.y} width={rect.w} height={1} fill={rect.fill} />
      ))}
    </svg>
  );
});

